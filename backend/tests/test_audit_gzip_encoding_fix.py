@pytest.mark.asyncio
async def test_empirical_litestar_stack_order_compression_is_inside_audit_middleware(monkeypatch):
    """Advisor-driven correction — every other test in this file
    SIMULATES the gzip-compressed shape by hand-building the ASGI
    messages a real `CompressionMiddleware` would send. This test
    instead builds a REAL, minimal `Litestar` app with the app's own
    `compression_config` (gzip, same backend as `backend/api/app.py`)
    and the real `AuditMiddleware`, and drives it through a real
    `AsyncTestClient` PATCH request — empirically proving the
    middleware-ordering claim this whole fix rests on (`AuditMiddleware`
    sits OUTSIDE/after `CompressionMiddleware` in Litestar's own
    `build_route_middleware_stack()`), rather than only reasoning about
    it from reading Litestar's source."""
    import gzip
    import json as _json

    from litestar import Litestar, Controller, patch as patch_route
    from litestar.config.compression import CompressionConfig
    from litestar.testing import AsyncTestClient

    from backend.api import audit as audit_mod

    written: dict = {}

    async def fake_write_audit(**kwargs):
        written.update(kwargs)

    class _Ctrl(Controller):
        path = "/api/admin/brokers"

        @patch_route("/{account:str}")
        async def update_account(self, account: str) -> dict:
            # A real route handler response — Litestar's own JSON
            # encoding + the real CompressionMiddleware (minimum_size=1
            # so this small test payload still compresses) sit BETWEEN
            # this return and AuditMiddleware's own send wrapper.
            return {"detail": "Broker ZG0790 updated to is_active=true padding padding padding"}

    app = Litestar(
        route_handlers=[_Ctrl],
        compression_config=CompressionConfig(backend="gzip", minimum_size=1),
        middleware=[audit_mod.AuditMiddleware()],
    )

    with monkeypatch.context() as m:
        m.setattr(audit_mod, "_write_audit", fake_write_audit)
        async with AsyncTestClient(app=app) as client:
            resp = await client.patch(
                "/api/admin/brokers/ZG0790",
                headers={"Accept-Encoding": "gzip"},
            )

    assert resp.status_code == 200
    # Empirical proof the real CompressionMiddleware actually ran on this
    # response — if it hadn't (e.g. if the ordering claim were wrong and
    # AuditMiddleware ran AFTER compression never happened), the test
    # below would pass for the wrong reason. Confirmed empirically: the
    # ASGI test transport does NOT strip `content-encoding` the way a
    # real network round-trip through some HTTP stacks might.
    assert resp.headers.get("content-encoding") == "gzip", (
        "the response was not actually gzip-compressed — this test would "
        "prove nothing about middleware ordering if it ran uncompressed"
    )
    # The real JSON body still decodes correctly on the client side
    # (httpx/the test transport decompresses transparently).
    assert resp.json()["detail"].startswith("Broker ZG0790 updated")
    # AuditMiddleware's OWN internal capture (not the client-visible
    # response) correctly decoded a CLEAN summary from what was, at its
    # own `send` wrapper, still gzip-compressed bytes.
    assert written.get("summary") == (
        "Broker ZG0790 updated to is_active=true padding padding padding"
    ), (
        f"expected a clean readable summary from AuditMiddleware's own "
        f"capture, got {written.get('summary')!r} — if this is gzip "
        f"garbage, the empirical ordering claim this fix rests on is wrong"
    )


@pytest.mark.asyncio
async def test_empirical_counterfactual_without_the_fix_summary_is_garbage(monkeypatch):
    """The counterfactual half of the empirical proof above — with
    `_audit_decode_body` patched to a no-op passthrough (reproducing the
    pre-fix code exactly), the SAME real Litestar app + real gzip
    compression + real AuditMiddleware must capture a GARBLED summary,
    not the clean string. This is what actually proves the test above
    exercises the real ordering bug, rather than passing for an
    unrelated reason (e.g. if compression hadn't actually run, both this
    test and the positive one would show a clean summary, and neither
    would mean anything)."""
    from litestar import Litestar, Controller, patch as patch_route
    from litestar.config.compression import CompressionConfig
    from litestar.testing import AsyncTestClient

    from backend.api import audit as audit_mod

    written: dict = {}

    async def fake_write_audit(**kwargs):
        written.update(kwargs)

    class _Ctrl(Controller):
        path = "/api/admin/brokers"

        @patch_route("/{account:str}")
        async def update_account(self, account: str) -> dict:
            return {"detail": "Broker ZG0790 updated to is_active=true padding padding padding"}

    app = Litestar(
        route_handlers=[_Ctrl],
        compression_config=CompressionConfig(backend="gzip", minimum_size=1),
        middleware=[audit_mod.AuditMiddleware()],
    )

    with monkeypatch.context() as m:
        m.setattr(audit_mod, "_write_audit", fake_write_audit)
        # Reproduces the pre-fix code path exactly: no gunzip at all.
        m.setattr(audit_mod, "_audit_decode_body", lambda body, enc: body)
        async with AsyncTestClient(app=app) as client:
            resp = await client.patch(
                "/api/admin/brokers/ZG0790",
                headers={"Accept-Encoding": "gzip"},
            )

    assert resp.status_code == 200
    assert resp.headers.get("content-encoding") == "gzip", (
        "sanity check — compression must still have run for this "
        "counterfactual to mean anything"
    )
    assert written.get("summary") != (
        "Broker ZG0790 updated to is_active=true padding padding padding"
    ), (
        "without the fix, the real middleware stack's own gzip-compressed "
        "bytes must NOT decode to the clean string — if they do, the "
        "positive test above isn't actually testing anything"
    )


@pytest.mark.asyncio
async def test_pre_fix_shape_would_have_produced_garbage_confirms_the_regression(monkeypatch):
    """Negative control — directly reproduces the ORIGINAL bug by
    calling `_audit_parse_summary` on the raw (still-gzipped) bytes, the
    exact thing the pre-fix code did. Confirms the fixed body differs
    from — and is strictly better than — the broken one, so this test
    file is actually exercising the real regression, not a no-op."""
    from backend.api.audit import _audit_parse_summary
    detail_text = "Broker ZG0790 updated to is_active=true"
    payload = json.dumps({"detail": detail_text}).encode("utf-8")
    compressed = gzip.compress(payload)

    broken_summary = _audit_parse_summary(compressed)
    assert broken_summary != detail_text, (
        "sanity check failed — gzip bytes decoded directly as text should "
        "never coincidentally match the real detail string"
    )
