"""2026-11-20 fix (F5) — `audit_log` writes were failing with
`CharacterNotInRepertoireError`, 414 times in one day, across every
mutating admin action (including the `is_active` toggles the live
ZG0790 CAPTCHA incident revolved around).

Root cause: `AuditMiddleware` sits OUTSIDE (further from the route
handler than) Litestar's own `compression_config` (gzip,
`backend/api/app.py`) in the ASGI middleware stack — confirmed via
`litestar/_asgi/routing_trie/mapping.py:build_route_middleware_stack()`,
which applies `CompressionMiddleware` before the app-level
`middleware=[...]` list. So `AuditMiddleware`'s `send` wrapper
intercepts the response body AFTER it has already been gzip-compressed
(for any response ≥ 500 bytes when the client sent `Accept-Encoding:
gzip`, true for essentially every real browser request), with
`Content-Encoding: gzip` already set. `_audit_parse_summary()` used to
decode those raw compressed bytes as UTF-8 text unconditionally,
producing garbage that Postgres' `TEXT` column rejected.

This file proves the fix end-to-end (a real gzip-compressed ASGI
response, run through the real `AuditMiddleware.handle()`, writes a
CLEAN, readable `summary`) and at the unit level (`_audit_decode_body`).
"""
import asyncio
import gzip
import json

import pytest


# ─────────────────────────────────────────────────────────────────────
# Unit tests — _audit_decode_body()
# ─────────────────────────────────────────────────────────────────────

def test_gzip_content_encoding_decompresses_body():
    from backend.api.audit import _audit_decode_body
    payload = b'{"detail": "Broker ZG0790 updated"}'
    compressed = gzip.compress(payload)
    assert _audit_decode_body(compressed, "gzip") == payload


def test_no_content_encoding_passes_through_unchanged():
    from backend.api.audit import _audit_decode_body
    payload = b'{"detail": "plain uncompressed body"}'
    assert _audit_decode_body(payload, None) == payload


def test_non_gzip_content_encoding_passes_through_unchanged():
    """Only gzip is handled (the only backend this app's CompressionConfig
    uses) — a different encoding value is left as-is rather than guessed at."""
    from backend.api.audit import _audit_decode_body
    payload = b"some br-encoded bytes"
    assert _audit_decode_body(payload, "br") == payload


def test_empty_body_passes_through_unchanged():
    from backend.api.audit import _audit_decode_body
    assert _audit_decode_body(b"", "gzip") == b""


def test_truncated_gzip_stream_degrades_to_empty_not_garbage():
    """`_BODY_CAP` can cut a large compressed response mid-stream. A
    truncated/corrupt gzip payload must degrade to `b""` (summary
    omitted) rather than raising, and — critically — must NEVER fall
    back to re-decoding the raw compressed bytes as text (that is the
    exact pre-fix bug)."""
    from backend.api.audit import _audit_decode_body
    payload = b'{"detail": "a fairly long response body so the gzip stream has real content"}'
    compressed = gzip.compress(payload)
    truncated = compressed[: len(compressed) // 2]
    assert _audit_decode_body(truncated, "gzip") == b""


# ─────────────────────────────────────────────────────────────────────
# End-to-end — a real admin mutation's gzip-compressed response
# ─────────────────────────────────────────────────────────────────────

async def _run_middleware_and_capture_write(monkeypatch, scope, next_app):
    """Run `AuditMiddleware.handle()` against `next_app`, capture the
    kwargs that would have been passed to `_write_audit` (the real DB
    insert), without touching a real database."""
    from backend.api import audit as audit_mod

    written: dict = {}

    async def fake_write_audit(**kwargs):
        written.update(kwargs)

    monkeypatch.setattr(audit_mod, "_write_audit", fake_write_audit)

    sent: list = []

    async def mock_send(message):
        sent.append(message)

    async def mock_receive():
        return {"type": "http.request", "body": b""}

    middleware = audit_mod.AuditMiddleware()
    before_tasks = asyncio.all_tasks()
    await middleware.handle(scope, mock_receive, mock_send, next_app)
    # _audit_schedule_write fires an out-of-band asyncio.create_task —
    # let it run to completion before asserting on `written`.
    new_tasks = asyncio.all_tasks() - before_tasks
    for t in new_tasks:
        await t
    return written, sent


@pytest.mark.asyncio
async def test_gzip_compressed_admin_mutation_writes_clean_readable_summary(monkeypatch):
    """THE key regression test — simulates exactly what Litestar's real
    middleware stack produces for a real admin PATCH response: gzip-
    compressed body + `Content-Encoding: gzip` header, generated by the
    route handler/CompressionMiddleware (inside AuditMiddleware's own
    `next_app`). Confirms the real admin-mutation shape the live
    incident hit (a `broker_accounts.is_active` toggle) now writes a
    clean, human-readable `summary` — not gzip garbage."""
    detail_text = "Broker ZG0790 updated to is_active=true"
    payload = json.dumps({"detail": detail_text}).encode("utf-8")
    compressed = gzip.compress(payload)

    async def next_app(scope, receive, send):
        await send({
            "type": "http.response.start",
            "status": 200,
            "headers": [
                (b"content-encoding", b"gzip"),
                (b"content-type", b"application/json"),
            ],
        })
        await send({"type": "http.response.body", "body": compressed})

    scope = {
        "type": "http",
        "method": "PATCH",
        "path": "/api/admin/brokers/ZG0790",
        "headers": [],
        "state": {"token_payload": {"sub": "admin", "role": "admin", "user_id": 1}},
    }

    written, sent = await _run_middleware_and_capture_write(monkeypatch, scope, next_app)

    assert written.get("summary") == detail_text, (
        f"expected a clean readable summary, got {written.get('summary')!r} — "
        f"this is the exact CharacterNotInRepertoireError-producing shape if "
        f"the gzip body were decoded as text unconverted"
    )
    assert written.get("status_code") == 200
    assert written.get("category") == "config.broker"
    # The response the client actually receives is untouched — the fix
    # only changes what AuditMiddleware itself decodes for its own
    # bookkeeping, never the bytes forwarded to `send`.
    body_msg = next(m for m in sent if m.get("type") == "http.response.body")
    assert body_msg["body"] == compressed


