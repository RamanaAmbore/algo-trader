class TestRenderDeploySync:
    def test_builds_a_real_header_when_identity_is_present(self):
        from backend.api.algo.event_agents import _render_deploy_sync

        rec = {"extra": {
            "title": "Ticker degraded", "body": "MCX ticker degraded.",
            "agent_name": "Ticker degraded", "agent_id": 11,
        }}
        title, body, tg = _render_deploy_sync(rec)
        assert body.startswith("Agent: Ticker degraded (#11)\n")
        assert "MCX ticker degraded." in body

    def test_stays_header_less_with_no_identity_never_shows_manual(self):
        """A system/infra alert with no resolved identity must never
        read 'Agent: manual' — that label means 'a human placed this
        order', which doesn't apply here."""
        from backend.api.algo.event_agents import _render_deploy_sync

        rec = {"extra": {"title": "Deploy out of sync", "body": "dev/main drifted."}}
        title, body, tg = _render_deploy_sync(rec)
        assert body == "dev/main drifted."
        assert "manual" not in body.lower()
        assert "Agent:" not in body
