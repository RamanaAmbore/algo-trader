"""Every alert gets a real "Alert: {name} (#{id})" header — closing the
"market close has no label" gap, 2026-11-03.

Operator: "why market close alert does not have alert label. it is
generated from alert agent?... Every alert should be generated by an
agent and follow similar format." Then, on audit: "audit all the
alerts and make sure every one of them is generated by alert agent. The
real functionality should add the messages to log with proper tags so
that the alert agent pick them... notification, format, tags, names,
message, everything is driven by tags, info levels, and messages in the
logs."

Root cause (confirmed, not assumed): the market open/close summary and
the 5 `generic_notice` producers (gtt_asymmetric, oco_double_fire,
ticker_recovered, ticker_degraded, deploy_out_of_sync, visitor_report)
were ALREADY log-driven and picked up by a real event agent
(SUMMARY_AGENT / the generic_notice agents) — they were never a
bypass. The header was missing only because `_render_summary()` called
`dispatch_payload()` with no `agent_name`/`agent_id`, and
`_render_deploy_sync()` built no header at all. CLAUDE.md documented
this as "Deliberate exception — agent-less summaries"; the operator's
new instruction overrides that exception.

Wave 0 (of the 4-wave plan the operator approved) fixes this WITHOUT
restructuring the dispatch layer or touching any of the ~8 renderers
that already build a correct header — see each function's own
docstring for why that narrower scope was chosen.

Covers:
  1. `send_summary(agent_name=..., agent_id=...)` threads both into the
     log record's extra — via a REAL `LogStoreHandler` attached to the
     real dispatch logger (not a mocked dispatch), confirming the
     record is not dropped by `_SKIP_PREFIXES`.
  2. `_render_summary()` passes the real identity to `dispatch_payload`
     — the rendered Telegram text contains "Alert:" + the name; with no
     identity, the output is byte-identical to before (no "Alert:"
     line, no regression for the common/no-agent case).
  3. (2026-11-06 superseded) `TestProcessSourceProducers`: each of the 8
     background-process producers (user registration, market status
     report, market summary, GTT reconciler, OCO watcher, ticker
     watchdog, visitor report, deploy sync) now logs a literal
     `source_type="process"` + a real process name — never a
     `get_agent_id_by_slug()` DB round-trip, which is DELETED along with
     `generic_notice_identity_extra()`/`_GENERIC_NOTICE_IDENTITY`.
  4. `_render_deploy_sync()`: builds a real "Agent: {name} (#{id})"
     header line when both are present in extras; stays header-less
     (byte-identical to before) when they're absent — never falls back
     to "Agent: manual", which would misdescribe a system/infra alert.
"""
from __future__ import annotations

import logging
from unittest.mock import AsyncMock

import pytest

from backend.shared.helpers import log_store


@pytest.mark.asyncio
async def test_send_summary_threads_agent_identity_through_a_real_log_handler():
    """Real LogStoreHandler, real logger — not a mocked dispatch. See
    test_log_store.py::test_order_failure_and_summary_records_reach_the_queue
    for why this exact mechanism (the `_SKIP_PREFIXES` logger-name trap)
    matters."""
    import pandas as pd
    from backend.shared.helpers import alert_utils

    h = log_store.LogStoreHandler()
    dispatch_logger = logging.getLogger("backend.api.algo.events")
    dispatch_logger.addHandler(h)
    dispatch_logger.setLevel(logging.INFO)
    try:
        alert_utils.send_summary(
            pd.DataFrame(), pd.DataFrame(), "03-Nov-26 15:45", "close", label="Equity",
            agent_name="Market summary", agent_id=42,
        )
    finally:
        dispatch_logger.removeHandler(h)

    rows = h.drain(10)
    summary_rows = [r for r in rows if r["extra"].get("alert_event") == "summary"]
    assert summary_rows, "summary record never reached the queue"
    assert summary_rows[0]["extra"].get("agent_name") == "Market summary"
    assert summary_rows[0]["extra"].get("agent_id") == 42


